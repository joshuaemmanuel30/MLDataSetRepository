# Import necessary libraries
import pandas as pd
from sklearn.linear_model import LinearRegression

# Step 1: Create a dataset
data = {
    'Size': [100, 200, 300, 400, 500],
    'Price': [50, 100, 150, 200, 250]
}

# Step 2: Convert dataset into a DataFrame
df = pd.DataFrame(data)

# Display the dataset
print("House Price Dataset:")
print(df)

# Step 3: Define independent and dependent variables
X = df[['Size']]       # House size (input)
y = df['Price']        # House price (output)

# Step 4: Create Linear Regression model
model = LinearRegression()

# Step 5: Train the model
model.fit(X, y)

# Step 6: Predict the price of a 350 sqm house
new_house = pd.DataFrame({'Size': [350]})
predicted_price = model.predict(new_house)

# Step 7: Display the prediction
print("\nPredicted price for a 350 sqm house:")
print(f"₦{predicted_price[0]:.2f} million")

# Display model parameters
print("\nModel Coefficient:", model.coef_[0])
print("Model Intercept:", model.intercept_)

